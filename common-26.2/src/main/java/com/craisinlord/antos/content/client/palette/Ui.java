    public static int alpha(int color, int alpha) {
        return (alpha & 255) << 24 | color & 0x00FFFFFF;
    }

    public static int mix(int first, int second, float amount) {
        int r = Math.round(((first >> 16) & 255) * (1 - amount) + ((second >> 16) & 255) * amount);
        int g = Math.round(((first >> 8) & 255) * (1 - amount) + ((second >> 8) & 255) * amount);
        int b = Math.round((first & 255) * (1 - amount) + (second & 255) * amount);
        return first & 0xFF000000 | r << 16 | g << 8 | b;
    }

    public static int icon(int pixel) {
        if (terminal && iconBase == ACCENT) return TerminalPalette.remap(pixel, theme);
        if (!greenish(pixel)) return pixel;
        return greenRamp(pixel, iconBase);
    }

    public static int proceduralWallpaper(int pixel) {
        if (terminal) return TerminalPalette.remap(pixel, theme);
        float level = Math.min(1.0F, ((pixel >> 8) & 255) / 128.0F);
        return pixel & 0xFF000000 | mix(DEEP, HOVER, level) & 0x00FFFFFF;
    }

    public static int wallpaperPixel(int argb) {
        int alpha = argb >>> 24;
        float luminance = (0.2126F * ((argb >> 16) & 255) + 0.7152F * ((argb >> 8) & 255) + 0.0722F * (argb & 255)) / 255.0F;
        int middle = mix(SURFACE, ACCENT, 0.45F);
        int color = luminance < 0.5F ? mix(BACKGROUND, middle, luminance * 2.0F) : mix(middle, TEXT_STRONG, (luminance - 0.5F) * 2.0F);
        return alpha << 24 | color & 0x00FFFFFF;
    }

