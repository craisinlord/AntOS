        FOCUS = accent;
        SURFACE = panel;
        BORDER = mix(window, text, 0.12F);
        BACKGROUND = window;
        DESKTOP = desktop;
        TITLE_BAR = panel;
        HOVER = mix(window, text, 0.10F);
        PANEL = mix(window, text, 0.05F);
        PANEL_ALT = mix(window, text, 0.03F);
        DEEP = mix(window, desktop, 0.60F);
        LINE = mix(window, text, 0.16F);
