    public static Preview preview(String look) {
        if (look.equals("terminal")) {
            applyTerminal();
        } else {
            int[] bases = PaletteColors.graphite();
            applyDerived(bases[PaletteColors.DESKTOP], bases[PaletteColors.WINDOW], bases[PaletteColors.PANEL], bases[PaletteColors.TEXT],
                    bases[PaletteColors.MUTED], theme.apply(0xFF65FF65), bases[PaletteColors.ERROR]);
        }
        Preview preview = new Preview(SURFACE, BACKGROUND, TITLE_BAR, BORDER_STRONG, TEXT_STRONG, TEXT, TEXT_MUTED, ACCENT, HOVER, LINE);
        refresh();
        return preview;
    }

