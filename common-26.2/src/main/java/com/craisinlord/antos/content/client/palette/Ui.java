    public static long wallpaperSignature() {
        long signature = 31L * BACKGROUND + SURFACE;
        signature = 31L * signature + TEXT_STRONG;
        signature = 31L * signature + (theme == ComputerTheme.RAINBOW ? System.currentTimeMillis() / 2000L : ACCENT);
        return signature;
    }

