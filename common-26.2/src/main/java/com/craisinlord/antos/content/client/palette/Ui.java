    private static boolean greenish(int color) {
        int r = (color >> 16) & 255;
        int g = (color >> 8) & 255;
        int b = color & 255;
        return Math.abs(r - b) <= 12 && g >= Math.max(r, b) && g > 0;
    }

    private static int greenRamp(int pixel, int base) {
        float green = ((pixel >> 8) & 255) / 255.0F;
        float white = Math.max(0.0F, Math.min(1.0F, ((((pixel >> 16) & 255) + (pixel & 255)) / 510.0F - 0.4F) / 0.6F));
        int color = mix(mix(BACKGROUND, base, green), TEXT_STRONG, white);
        return pixel & 0xFF000000 | color & 0x00FFFFFF;
    }

